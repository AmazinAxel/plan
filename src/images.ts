import type { Database } from "bun:sqlite";
import type { Data } from "./plan-store";

// Images live in the `images` table of the same SQLite file as the data blob,
// one row per image: the bytes, their content type, and the upload time. The
// blob itself only ever stores the uuid — it is re-PUT in full on every save,
// so bytes can never go in it.
export const MAX_IMAGE_BYTES = 10 * 1024 * 1024;
export const ALLOWED_TYPES = new Set([
  "image/webp", "image/png", "image/jpeg", "image/gif", "image/avif",
]);

export interface StoredImage { ct: string; at: number; bytes: Uint8Array }

// Ids are generated by crypto.randomUUID(); anything else is turned away before
// it reaches the database.
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
export const isImageId = (id: string): boolean => UUID_RE.test(id);

// An upload is stored before the save that references it, so there is always a
// window in which a live image looks like garbage — and it stretches as far as
// the save can be delayed, which is unbounded if the client goes offline
// holding a pending write.
//
// The grace is deliberately far longer than that window needs to be. Sweeping
// is only the backstop for genuinely abandoned uploads, which are rare, so
// collecting one a day late costs nothing — while sweeping too eagerly would
// delete an image whose reference was merely in transit, which is unrecoverable
// and exactly the failure this whole design exists to prevent.
const SWEEP_GRACE_MS = 24 * 60 * 60 * 1000;
export const SWEEP_INTERVAL_MS = 60 * 60 * 1000;

// How long after upload a client may still disown its own image (see the DELETE
// route). Long enough for a slow upload to finish and be abandoned, short
// enough that the endpoint can't be pointed at an established image.
export const DISOWN_WINDOW_MS = 60 * 60 * 1000;

export function putImage(db: Database, id: string, ct: string, bytes: Uint8Array): void {
  db.query("INSERT INTO images (id, ct, at, bytes) VALUES (?, ?, ?, ?)").run(id, ct, Date.now(), bytes);
}

export function getImage(db: Database, id: string): StoredImage | null {
  return db.query<StoredImage, [string]>("SELECT ct, at, bytes FROM images WHERE id = ?").get(id);
}

export function imageMeta(db: Database, id: string): { at: number } | null {
  return db.query<{ at: number }, [string]>("SELECT at FROM images WHERE id = ?").get(id);
}

export function deleteImage(db: Database, id: string): void {
  db.query("DELETE FROM images WHERE id = ?").run(id);
}

/** Every image id referenced anywhere in the blob. */
export function imageRefs(data: Data): Set<string> {
  const refs = new Set<string>();
  if (!Array.isArray(data?.plans)) return refs;
  for (const plan of data.plans) {
    if (!Array.isArray(plan?.lists)) continue;
    for (const list of plan.lists) {
      if (!Array.isArray(list?.entries)) continue;
      for (const entry of list.entries) {
        if (typeof entry?.image === "string" && entry.image) refs.add(entry.image);
      }
    }
  }
  return refs;
}

/**
 * Delete the images that `next` drops relative to `current`.
 *
 * This is the primary no-orphan mechanism: every way an image can stop being
 * referenced — detach, entry/list/plan delete, undo, overwriting an entry's
 * image — reaches the server as one blob replacing another, so the set
 * difference catches all of them without the client having to ask. Run it in
 * the same transaction as the write of `next`.
 */
export function reconcile(db: Database, current: Data, next: Data): void {
  const keep = imageRefs(next);
  for (const id of imageRefs(current)) if (!keep.has(id)) deleteImage(db, id);
}

/**
 * Full reconciliation against the live blob: delete every stored image that
 * nothing references.
 *
 * `reconcile` covers state *transitions*, but an image can become unreferenced
 * without one — the upload succeeds and then the tab closes, or the save that
 * would have carried the reference loses a 409 to another device. In both the
 * id never appears in any blob, so no diff can see it. This is the backstop for
 * exactly those windows. Skips young rows, so it can never race an upload that
 * is still in flight.
 */
export function sweep(db: Database, data: Data): void {
  const keep = imageRefs(data);
  const old = db.query<{ id: string }, [number]>("SELECT id FROM images WHERE at < ?").all(Date.now() - SWEEP_GRACE_MS);
  for (const { id } of old) if (!keep.has(id)) deleteImage(db, id);
}
